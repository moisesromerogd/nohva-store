-- Nohva Platform: additive core schema (review before applying)
-- This migration intentionally does NOT alter the existing catalog tables or policies.
-- Apply only after confirming the Auth users and testing against a staging project.

create table if not exists public.platform_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null,
  role text not null default 'employee' check (role in ('owner','employee')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create or replace function public.platform_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role
  from public.platform_profiles
  where user_id = auth.uid() and active = true
  limit 1;
$$;

create or replace function public.platform_is_owner()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(public.platform_role() = 'owner', false);
$$;

create or replace function public.platform_profile_bootstrap()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.platform_profiles (user_id, display_name, role)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data->>'display_name',''), split_part(coalesce(new.email,''),'@',1), 'Usuario'),
    'employee'
  )
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists platform_profile_after_signup on auth.users;
create trigger platform_profile_after_signup
after insert on auth.users
for each row execute procedure public.platform_profile_bootstrap();

create table if not exists public.platform_sales (
  id uuid primary key default gen_random_uuid(),
  sale_number bigint generated by default as identity unique,
  seller_id uuid not null default auth.uid() references auth.users(id),
  client_name text,
  client_phone text,
  channel text,
  sale_date timestamptz not null default now(),
  due_date date,
  total_usd numeric(12,2) not null check (total_usd >= 0),
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.platform_sale_items (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null references public.platform_sales(id) on delete cascade,
  product_id text,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price_usd numeric(12,2) not null check (unit_price_usd >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.platform_payments (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null references public.platform_sales(id) on delete cascade,
  recorded_by uuid not null default auth.uid() references auth.users(id),
  amount_usd numeric(12,2) not null check (amount_usd > 0),
  payment_method text not null,
  amount_bs numeric(14,2),
  exchange_rate numeric(14,4),
  reference text,
  paid_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists platform_sales_seller_date_idx
  on public.platform_sales (seller_id, sale_date desc);
create index if not exists platform_sale_items_sale_idx
  on public.platform_sale_items (sale_id);
create index if not exists platform_payments_sale_idx
  on public.platform_payments (sale_id, paid_at desc);

alter table public.platform_profiles enable row level security;
alter table public.platform_sales enable row level security;
alter table public.platform_sale_items enable row level security;
alter table public.platform_payments enable row level security;

drop policy if exists platform_profiles_read_self_or_owner on public.platform_profiles;
create policy platform_profiles_read_self_or_owner
on public.platform_profiles for select to authenticated
using (user_id = auth.uid() or public.platform_is_owner());

drop policy if exists platform_sales_read_owner_or_seller on public.platform_sales;
create policy platform_sales_read_owner_or_seller
on public.platform_sales for select to authenticated
using (public.platform_is_owner() or seller_id = auth.uid());

drop policy if exists platform_sales_insert_as_self on public.platform_sales;
create policy platform_sales_insert_as_self
on public.platform_sales for insert to authenticated
with check (seller_id = auth.uid() and public.platform_role() in ('owner','employee'));

drop policy if exists platform_sales_owner_update on public.platform_sales;
create policy platform_sales_owner_update
on public.platform_sales for update to authenticated
using (public.platform_is_owner()) with check (public.platform_is_owner());

drop policy if exists platform_sales_owner_delete on public.platform_sales;
create policy platform_sales_owner_delete
on public.platform_sales for delete to authenticated
using (public.platform_is_owner());

drop policy if exists platform_sale_items_read_parent_sale on public.platform_sale_items;
create policy platform_sale_items_read_parent_sale
on public.platform_sale_items for select to authenticated
using (
  exists (
    select 1 from public.platform_sales s
    where s.id = sale_id and (public.platform_is_owner() or s.seller_id = auth.uid())
  )
);

drop policy if exists platform_sale_items_insert_parent_sale on public.platform_sale_items;
create policy platform_sale_items_insert_parent_sale
on public.platform_sale_items for insert to authenticated
with check (
  exists (
    select 1 from public.platform_sales s
    where s.id = sale_id and (public.platform_is_owner() or s.seller_id = auth.uid())
  )
);

drop policy if exists platform_sale_items_owner_update on public.platform_sale_items;
create policy platform_sale_items_owner_update
on public.platform_sale_items for update to authenticated
using (public.platform_is_owner()) with check (public.platform_is_owner());

drop policy if exists platform_sale_items_owner_delete on public.platform_sale_items;
create policy platform_sale_items_owner_delete
on public.platform_sale_items for delete to authenticated
using (public.platform_is_owner());

drop policy if exists platform_payments_read_parent_sale on public.platform_payments;
create policy platform_payments_read_parent_sale
on public.platform_payments for select to authenticated
using (
  exists (
    select 1 from public.platform_sales s
    where s.id = sale_id and (public.platform_is_owner() or s.seller_id = auth.uid())
  )
);

drop policy if exists platform_payments_insert_self_parent_sale on public.platform_payments;
create policy platform_payments_insert_self_parent_sale
on public.platform_payments for insert to authenticated
with check (
  recorded_by = auth.uid()
  and exists (
    select 1 from public.platform_sales s
    where s.id = sale_id and (public.platform_is_owner() or s.seller_id = auth.uid())
  )
);

drop policy if exists platform_payments_owner_update on public.platform_payments;
create policy platform_payments_owner_update
on public.platform_payments for update to authenticated
using (public.platform_is_owner()) with check (public.platform_is_owner());

drop policy if exists platform_payments_owner_delete on public.platform_payments;
create policy platform_payments_owner_delete
on public.platform_payments for delete to authenticated
using (public.platform_is_owner());

